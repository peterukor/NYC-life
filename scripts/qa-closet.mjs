// QA: start broke, open the closet at home (mirror view), browse tabs, save an outfit.
// Screens go to test-results/closet-*.png.
import puppeteer from 'puppeteer-core';
const browser = await puppeteer.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', headless: true, args: ['--no-sandbox', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage();
await page.setViewport({ width: 390, height: 780, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
await page.goto('http://localhost:4173/?qa=1&hour=11', { waitUntil: 'load' });
await page.evaluate(() => localStorage.clear());
await page.reload({ waitUntil: 'load' });
await page.waitForSelector('#ob-year', { timeout: 30000 });
await page.select('#ob-year', '1995');
await page.type('#ob-name', 'Jack');
await page.$eval('[data-origin="poor"]', (el) => el.click());
await page.$eval('#ob-go', (el) => el.click());
await wait(3500);
const owned = await page.evaluate(() => window.__nyc.wardrobe());
console.log('broke closet:', owned.filter((id) => !id.startsWith('hair_')).join(', '));
await page.evaluate(() => window.__nyc.closet());
await wait(1200);
await page.screenshot({ path: 'test-results/closet-tops.png' });
const click = async (sel) => { await page.$eval(sel, (el) => el.click()); await wait(900); };
await click('[data-wear="flannel"]');
await page.screenshot({ path: 'test-results/closet-flannel.png' });
await click('[data-tab="shoes"]');
await click('[data-wear="slides"]');
await click('[data-tab="hat"]');
await click('[data-wear="beanie"]');
await click('[data-color="#e9c46a"]');
await page.screenshot({ path: 'test-results/closet-beanie.png' });
await click('[data-turn]');
await click('[data-turn]');
await page.screenshot({ path: 'test-results/closet-back.png' });
await click('[data-tab="outfits"]');
await click('[data-save="0"]');
await page.screenshot({ path: 'test-results/closet-outfits.png' });
await page.$eval('.sheet .close', (el) => el.click());
await wait(900);
await page.screenshot({ path: 'test-results/closet-closed.png' });
console.log('errors:', [...new Set(errors)].join('\n') || 'none');
await browser.close();

// =====================================================================
// build-geo.mjs — turns the real NYC borough boundaries into the small
// outline file the game uses (src/data/geo/nyc-boroughs.ts).
//
// Source: NYC Department of City Planning borough boundaries (NYC Open
// Data, via github.com/dwillis/nyc-maps), saved in scripts/geo-src/.
//
// Steps: project lat/lon to game metres (src/world/geo-proj.ts uses the
// SAME numbers — keep them in sync), drop tiny islands, simplify with
// Douglas–Peucker so each borough is a few hundred points.
//   node scripts/build-geo.mjs
// =====================================================================
import { readFileSync, writeFileSync } from 'node:fs';

// Must match src/world/geo-proj.ts.
const ORIGIN = { lat: 40.758, lon: -73.9855 }; // Times Square = (0, 0)
const ROTATE_DEG = 29; // Manhattan's grid is 29° off true north; this makes avenues run up the screen
const SCALE = 0.2; // game metres per real metre (NYC compressed 5×)

const th = (ROTATE_DEG * Math.PI) / 180;
const cosLat = Math.cos((ORIGIN.lat * Math.PI) / 180);
function project(lon, lat) {
  const E = (lon - ORIGIN.lon) * cosLat * 111320;
  const N = (lat - ORIGIN.lat) * 110540;
  const e = E * Math.cos(th) - N * Math.sin(th);
  const n = E * Math.sin(th) + N * Math.cos(th);
  return [e * SCALE, -n * SCALE];
}

function area(ring) {
  let a = 0;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) a += (ring[j][0] + ring[i][0]) * (ring[j][1] - ring[i][1]);
  return Math.abs(a / 2);
}

function simplify(pts, tol) {
  if (pts.length < 3) return pts;
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    let best = -1, bi = -1;
    const [ax, az] = pts[a], [bx, bz] = pts[b];
    const dx = bx - ax, dz = bz - az, L = Math.hypot(dx, dz) || 1;
    for (let i = a + 1; i < b; i++) {
      const d = Math.abs((pts[i][0] - ax) * dz - (pts[i][1] - az) * dx) / L;
      if (d > best) { best = d; bi = i; }
    }
    if (best > tol) { keep[bi] = 1; stack.push([a, bi], [bi, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}

const IDS = { Manhattan: 'manhattan', Brooklyn: 'brooklyn', Queens: 'queens', Bronx: 'bronx', 'Staten Island': 'statenIsland' };
const src = JSON.parse(readFileSync(new URL('./geo-src/nyc-boroughs.geojson', import.meta.url)));
const out = { origin: ORIGIN, rotateDeg: ROTATE_DEG, scale: SCALE, boroughs: {} };
for (const f of src.features) {
  const id = IDS[f.properties.BoroName];
  const polys = f.geometry.type === 'MultiPolygon' ? f.geometry.coordinates : [f.geometry.coordinates];
  const rings = polys.map((p) => p[0].map(([lon, lat]) => project(lon, lat)));
  const big = Math.max(...rings.map(area));
  // Keep the main land and the bigger islands (Roosevelt, Governors, Randall's…).
  // A closed ring starts and ends on the same point, so simplify it in two halves.
  const simplifyRing = (r) => {
    const h = Math.floor(r.length / 2);
    return [...simplify(r.slice(0, h + 1), 3).slice(0, -1), ...simplify(r.slice(h), 3)];
  };
  const kept = rings.filter((r) => area(r) > Math.max(big * 0.004, 2000)).map((r) => simplifyRing(r).map(([x, z]) => [Math.round(x * 10) / 10, Math.round(z * 10) / 10]));
  out.boroughs[id] = kept.sort((a, b) => area(b) - area(a));
  console.log(id, kept.length, 'rings', kept.map((r) => r.length).join('/'), 'points');
}
const header = '// GENERATED by scripts/build-geo.mjs from NYC borough boundaries (NYC Open Data). Do not edit by hand.\n';
writeFileSync(new URL('../src/data/geo/nyc-boroughs.ts', import.meta.url), `${header}export const NYC_GEO: { origin: { lat: number; lon: number }; rotateDeg: number; scale: number; boroughs: Record<string, [number, number][][]> } = ${JSON.stringify(out)};\n`);
console.log('wrote src/data/geo/nyc-boroughs.ts');

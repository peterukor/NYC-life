// Vite build settings.
//
// The game loads in pieces (Peter, 2026-10-15: "load the game in pieces"):
//
//   • index.html paints the NY loading screen by itself, before any script.
//   • three.js (the 3D engine, ~2/3 of the code) is its own file and the
//     game is another. File names carry a content hash, so after an update
//     a returning player only downloads the pieces that actually changed.
//   • sw.js (a service worker, generated below with the list of this
//     build's files) keeps a copy of everything on the device: return
//     visits start from the phone, not the network, and work offline.
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { defineConfig, type Plugin } from 'vite';

/** Emits sw.js: precaches this build's files; a new build = a new cache. */
function serviceWorker(): Plugin {
  return {
    name: 'nyc-sw',
    apply: 'build',
    generateBundle(_opts, bundle) {
      const files = Object.keys(bundle).filter((f) => !f.endsWith('.map'));
      // Models and other files copied as-is from public/.
      const walk = (dir: string, base = ''): string[] =>
        readdirSync(dir).flatMap((f) => (statSync(join(dir, f)).isDirectory() ? walk(join(dir, f), `${base}${f}/`) : [`${base}${f}`]));
      const pub = walk('public');
      const hash = createHash('sha256');
      for (const f of files.sort()) {
        const item = bundle[f];
        hash.update(f);
        hash.update(item.type === 'chunk' ? item.code : typeof item.source === 'string' ? item.source : Buffer.from(item.source));
      }
      // public/ files keep their names, so tag each with a hash of its content:
      // an unchanged model carries over from the old cache instead of re-downloading.
      const pubTagged = pub.map((f) => {
        const h = createHash('sha256').update(readFileSync(join('public', f))).digest('hex').slice(0, 10);
        hash.update(f + h);
        return `${f}?v=${h}`;
      });
      const version = hash.digest('hex').slice(0, 12);
      const precache = ['./', ...files.filter((f) => f !== 'index.html'), ...pubTagged].map((f) => (f === './' ? f : `./${f}`));
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: SW_SOURCE.replace('__VERSION__', version).replace('__PRECACHE__', JSON.stringify(precache)) });
    },
  };
}

// The service worker itself (plain JS, runs outside the page).
const SW_SOURCE = `// NYC Life service worker: generated by vite.config.ts, do not edit.
const VERSION = '__VERSION__';
const CACHE = 'nyc-life-' + VERSION;
const PRECACHE = __PRECACHE__;

self.addEventListener('install', (e) => {
  // A new build takes over straight away, so a refresh shows the update.
  self.skipWaiting();
  // Pieces this device already has (same name + hash) are copied over from
  // the previous build's cache; only new or changed ones are downloaded.
  e.waitUntil((async () => {
    const c = await caches.open(CACHE);
    await Promise.all(PRECACHE.map(async (u) => {
      const old = u === './' ? null : await caches.match(u);
      if (old) return c.put(u, old);
      const res = await fetch(u, { cache: 'reload' });
      if (res.ok) await c.put(u, res);
    })).catch(() => {});
  })());
});

self.addEventListener('activate', (e) => {
  // Keep this build and the one before it (a tab still running the old
  // build can finish loading its pieces); drop anything older.
  e.waitUntil((async () => {
    const keep = new Set([CACHE]);
    const names = (await caches.keys()).filter((n) => n.startsWith('nyc-life-') && n !== CACHE);
    const stamped = await Promise.all(names.map(async (n) => [n, Number((await (await caches.open(n)).match('./__stamp'))?.headers.get('x-t') ?? 0)]));
    stamped.sort((a, b) => b[1] - a[1]);
    if (stamped[0]) keep.add(stamped[0][0]);
    await Promise.all(names.filter((n) => !keep.has(n)).map((n) => caches.delete(n)));
    await (await caches.open(CACHE)).put('./__stamp', new Response('', { headers: { 'x-t': String(Date.now()) } }));
    await self.clients.claim();
  })());
});

const timeout = (ms) => new Promise((_, no) => setTimeout(() => no(new Error('timeout')), ms));

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  // The page itself: the network first (so a refresh gets the newest
  // build), the saved copy when offline or the network is very slow.
  if (req.mode === 'navigate') {
    e.respondWith((async () => {
      try {
        const res = await Promise.race([fetch(req), timeout(4000)]);
        if (res.ok) (await caches.open(CACHE)).put('./', res.clone());
        return res;
      } catch {
        return (await caches.match('./')) || (await caches.match(req)) || Response.error();
      }
    })());
    return;
  }
  // Fonts: the saved copy, refreshed in the background.
  if (url.host === 'fonts.googleapis.com' || url.host === 'fonts.gstatic.com') {
    e.respondWith((async () => {
      const c = await caches.open('nyc-life-fonts');
      const hit = await c.match(req);
      const net = fetch(req).then((res) => { if (res.ok || res.type === 'opaque') c.put(req, res.clone()); return res; }).catch(() => hit);
      return hit || net;
    })());
    return;
  }
  if (url.origin !== self.location.origin) return;
  // Game files: from the device when we have them, else the network (and keep a copy).
  e.respondWith((async () => {
    // This build's copy first (an older cache could hold an older model).
    const hit = (await (await caches.open(CACHE)).match(req, { ignoreSearch: true })) || (await caches.match(req, { ignoreSearch: true }));
    if (hit) return hit;
    const res = await fetch(req);
    if (res.ok) (await caches.open(CACHE)).put(req, res.clone());
    return res;
  })());
});
`;

export default defineConfig({
  base: './',
  plugins: [serviceWorker()],
  build: {
    target: 'es2022',
    // three.js is one big file on purpose (cached separately); silence the size warning.
    chunkSizeWarningLimit: 1200,
    reportCompressedSize: true,
    rolldownOptions: {
      output: {
        codeSplitting: {
          groups: [{ name: 'three', test: /node_modules[\\/](three|meshoptimizer)[\\/]/ }],
        },
      },
    },
  },
});
